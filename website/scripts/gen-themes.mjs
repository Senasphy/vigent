// Writes src/lib/themes.ts from vigent's own built-in themes, so the site
// shows exactly the colors vigent draws. Run from website/ after building
// vigent at the repo root (npm run build):  node scripts/gen-themes.mjs
import * as fs from "node:fs";
import { BUILTIN_THEMES, Painter } from "../../dist/theme.js";

// what the drawing of vigent paints, and the highlight group each comes from
const ROLES = {
  bg: ["Normal", "bg"],
  fg: ["Normal", "fg"],
  side: ["VigentSidebar", "bg"],
  sep: ["WinSeparator", "fg"],
  bar: ["StatusLine", "bg"],
  barFg: ["StatusLine", "fg"],
  dim: ["Comment", "fg"],
  title: ["Title", "fg"],
  str: ["String", "fg"],
  user: ["VigentUser", "fg"],
  tool: ["VigentTool", "fg"],
  link: ["Function", "fg"],
  spin: ["VigentSpinner", "fg"],
  modeBg: ["VigentModeNormal", "bg"],
  modeFg: ["VigentModeNormal", "fg"],
  float: ["NormalFloat", "bg"],
  sel: ["PmenuSel", "bg"],
  selFg: ["PmenuSel", "fg"],
};

const out = {};
for (const [name, theme] of Object.entries(BUILTIN_THEMES)) {
  const p = new Painter(theme);
  const t = { background: theme.background ?? "dark", transparent: !!theme.transparent };
  for (const [role, [group, key]] of Object.entries(ROLES)) {
    const v = p.attr(group)[key];
    if (typeof v === "string" && v.startsWith("#")) t[role] = v;
  }
  out[name] = t;
}

const body = `/**
 * vigent's ${Object.keys(out).length} built-in colorschemes, as the drawing of vigent paints them.
 * Generated by scripts/gen-themes.mjs from vigent's own theme code: don't edit by hand.
 */
export interface ThemeColors {
  background: "dark" | "light";
  transparent: boolean;
${Object.keys(ROLES).map((r) => `  ${r}?: string;`).join("\n")}
}

export const THEMES: Record<string, ThemeColors> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(new URL("../src/lib/themes.ts", import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} themes`);
